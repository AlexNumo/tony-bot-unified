-- Supabase Schema for TonyBot Unified Platform («Точка переходу»)

-- 1. Таблиця користувачів
CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT PRIMARY KEY,
    username TEXT,
    first_name TEXT,
    last_name TEXT,
    phone TEXT,
    status TEXT DEFAULT 'free', -- free, base, support, vip
    current_day INT DEFAULT 1,
    avatar_url TEXT,
    utm_source TEXT,
    utm_medium TEXT,
    is_blocked BOOLEAN DEFAULT FALSE,
    join_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    last_active TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Таблиця тарифних пакетів
CREATE TABLE IF NOT EXISTS packages (
    id TEXT PRIMARY KEY, -- base, support, vip
    name TEXT NOT NULL,
    tag TEXT NOT NULL,
    price TEXT NOT NULL,
    old_price TEXT,
    desc_text TEXT,
    features JSONB,
    available_places INT
);

-- 3. Таблиця лідів (заявок на участь)
CREATE TABLE IF NOT EXISTS leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id) ON DELETE CASCADE,
    package_name TEXT NOT NULL,
    status TEXT DEFAULT 'pending', -- pending, paid, cancelled
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Таблиця результатів тесту (7 питань)
CREATE TABLE IF NOT EXISTS test_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id) ON DELETE CASCADE,
    score INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. Таблиця листування (історія чату користувача з ботом/ШІ/адміном)
CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id) ON DELETE CASCADE,
    direction TEXT NOT NULL, -- user, bot, admin, system
    text TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. Журнал доставки занять курсу
CREATE TABLE IF NOT EXISTS course_progress_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id) ON DELETE CASCADE,
    day_num INT NOT NULL,
    delivery_type TEXT DEFAULT 'auto', -- auto, manual
    status TEXT NOT NULL, -- sent, failed
    error_message TEXT,
    sent_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 7. Дії користувача (аналітика дій)
CREATE TABLE IF NOT EXISTS user_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id) ON DELETE CASCADE,
    action_type TEXT NOT NULL,
    target_element TEXT,
    metadata JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

